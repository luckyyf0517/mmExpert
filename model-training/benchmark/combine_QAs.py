"""
Combine partial QA files generated by parallel workers.
"""

import os
import json
import argparse
from glob import glob


def combine_qa_files(output_dir, split):
    """Combine all JSON files in split_QAs directory into one file."""

    qa_dir = os.path.join(output_dir, f"{split}_QAs")
    pattern = os.path.join(qa_dir, "part_*.json")
    part_files = sorted(glob(pattern))

    if not part_files:
        print(f"No part files found in {qa_dir}")
        return 0

    print(f"Found {len(part_files)} part files for {split}:")
    for file in part_files:
        print(f"  - {file}")

    combined_data = {}

    for part_file in part_files:
        print(f"Processing {part_file}...")
        with open(part_file, 'r', encoding='utf-8') as f:
            data = json.load(f)
            combined_data.update(data)

    # Save combined file
    output_file = os.path.join(output_dir, f"{split}_QAs.json")
    with open(output_file, 'w', encoding='utf-8') as f:
        json.dump(combined_data, f, indent=2, ensure_ascii=False)

    print(f"Combined {len(combined_data)} items into {output_file}")
    return len(combined_data)


def main():
    parser = argparse.ArgumentParser(description='Combine partial QA files')
    parser.add_argument('--output_dir', type=str, default='./output',
                        help='Directory containing QA partial files')
    parser.add_argument('--splits', type=str, nargs='+', default=['train', 'test'],
                        help='Splits to combine')
    args = parser.parse_args()

    total = 0
    for split in args.splits:
        print(f"\n=== Combining {split} split ===")
        count = combine_qa_files(args.output_dir, split)
        total += count

    print("\n=== Summary ===")
    print(f"Total items combined: {total}")


if __name__ == "__main__":
    main()
